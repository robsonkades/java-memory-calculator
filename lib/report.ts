import type { DiagnoseResult } from './diagnose';

const FINDING_TEXT: Record<string, (v: Record<string, number>) => string> = {
    'vm-threads': (v) => `NMT tracks ${v.nmt} threads while the dump lists ${v.dump} Java threads — the other ${v.delta} are VM-internal (GC, JIT, service threads).`,
    'stacks': (v) => `Thread stacks: ${v.reserved} MiB reserved upper bound (dump count × 1 MiB) vs ${v.committed} MiB actually committed per NMT.`,
    'rss-gap': (v) => `Measured RSS ${v.rss} MiB vs NMT committed ${v.committed} MiB — ${v.delta >= 0 ? '+' : ''}${v.delta} MiB outside the JVM's accounting (glibc arenas, JNI, mapped files).`,
    'heap-vs-live': (v) => `Live set ${v.live} MiB vs committed heap ${v.heap} MiB — recommended heap ≈ ${v.recommended} MiB (live × 3).`,
    'coh-savings': (v) => `Compact Object Headers would save ≈ ${v.savings} MiB${v.pct !== undefined ? ` (${v.pct}% of the committed heap)` : ''}.`,
    'off-peak': (v) => `Off-peak snapshot: the Java Heap peaked at ${v.peak} MiB but sits at ${v.now} MiB — size on the peak, not on this total.`,
};

/**
 * Ticket-ready Markdown summary of a diagnosis session. Always English —
 * incident reports travel across teams.
 */
export function buildMarkdownReport(result: DiagnoseResult, headroomPercent: number): string {
    const { parsed, findings } = result;
    const lines: string[] = [
        '# JVM memory diagnosis — jvm.expert',
        '',
        `Sources analyzed: ${result.sourceCount}/5.`,
        '',
    ];

    if (result.consolidatedLimitMiB !== undefined) {
        lines.push(`## Recommended container limit: ${result.consolidatedLimitMiB} Mi`,
            '',
            `max(NMT committed, measured RSS) + ${headroomPercent}% headroom.`,
            '');
    }

    if (findings.length > 0) {
        lines.push('## Cross-checks', '');
        for (const finding of findings) {
            lines.push(`- **[${finding.severity}]** ${FINDING_TEXT[finding.id]?.(finding.values) ?? finding.id}`);
        }
        lines.push('');
    }

    if (parsed.nmt) {
        lines.push('## Native Memory Tracking', '',
            `Committed total: ${(parsed.nmt.totalCommittedKiB / 1024).toFixed(1)} MiB · reserved ${(parsed.nmt.totalReservedKiB / 1024).toFixed(1)} MiB.`,
            '', '| Category | Committed (MiB) |', '| --- | ---: |');
        for (const category of [...parsed.nmt.categories].sort((a, b) => b.committedKiB - a.committedKiB).slice(0, 10)) {
            lines.push(`| ${category.name} | ${(category.committedKiB / 1024).toFixed(1)} |`);
        }
        lines.push('');
    }

    if (parsed.gclog) {
        const g = parsed.gclog;
        lines.push('## GC log', '',
            `Pauses: ${g.pauseCount}${g.zgc ? ` · ZGC collections: ${g.zgc.collections.length} (max STW ${g.zgc.maxPauseMs.toFixed(3)} ms)` : ''} · live set ${g.liveSetMiB} MiB (${g.liveSetSource}) · recommended heap ${g.recommendedHeapMiB} MiB.`,
            '');
    }

    if (parsed.threads) {
        lines.push('## Threads', '',
            `${parsed.threads.totalThreads} Java threads (${parsed.threads.daemonThreads} daemon) · reserved stacks ≈ ${parsed.threads.stackReservedMiB} MiB.`,
            '');
    }

    if (parsed.smaps) {
        const rss = parsed.smaps.kind === 'rollup' ? parsed.smaps.rssKiB : parsed.smaps.totalRssKiB;
        lines.push('## smaps', '', `Measured RSS: ${(rss / 1024).toFixed(1)} MiB.`, '');
    }

    if (parsed.histogram) {
        lines.push('## Heap histogram', '',
            `${parsed.histogram.totalInstances.toLocaleString('en-US')} instances · ${(parsed.histogram.totalBytes / (1024 * 1024)).toFixed(1)} MiB · top class ${parsed.histogram.rows[0].className}.`,
            '');
    }

    lines.push('---', '', 'Generated by [jvm.expert](https://jvm.expert) /diagnose.');
    return lines.join('\n');
}
